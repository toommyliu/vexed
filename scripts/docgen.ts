const renderApiOverview = (
  helpers: readonly MemberDoc[],
  namespaces: readonly ApiNamespace[],
): string => {
  const typeLinks = new Map<string, string>();
  const lines = [
    frontmatter(
      "API Namespace",
      "Generated vexed core script API namespace reference.",
      "API",
    ),
    "",
    GENERATED_HEADER,
    "",
    "`api` contains core game and service APIs. Feature controls live beside it on the script context as `autoZone` and `autoRelogin`.",
    "",
    "## Namespaces",
    "",
    "| Namespace | Source Type |",
    "| --- | --- |",
    ...namespaces.map(
      (namespace) =>
        `| [\`api.${namespace.name}\`](${namespace.href}) | \`${namespace.sourceType}\` |`,
    ),
    "",
    "## Helpers",
    "",
  ];

  for (const helper of helpers) {
    renderMember(lines, helper, typeLinks);
  }

  return finalizeMarkdown(lines);
};

const renderGroup = (group: ApiGroup): string => {
  const typeLinks = buildTypeLinks(group.types);
  const lines = [
    frontmatter(
      group.title,
      `Generated vexed scripting reference for ${group.contextPath}.`,
      group.label,
    ),
    "",
    GENERATED_HEADER,
    "",
    group.summary,
    "",
  ];

  if (group.members.length > 0) {
    const hasSummaries = group.members.some((member) => member.summary !== "");
    lines.push("## Reference Index", "");
    if (hasSummaries) {
      lines.push("| Member | Summary |", "| --- | --- |");
    } else {
      lines.push("| Member |", "| --- |");
    }
    for (const member of group.members) {
      const memberLink = `[\`${member.path}\`](#${memberAnchor(member.path)})`;
      lines.push(
        hasSummaries
          ? `| ${memberLink} | ${escapeTableCell(member.summary)} |`
          : `| ${memberLink} |`,
      );
    }
    lines.push("", "## Members", "");
    for (const member of group.members) {
      renderMember(lines, member, typeLinks);
    }
  }

  renderTypes(lines, group.types, typeLinks);
  return finalizeMarkdown(lines);
};

const renderFiles = (
  options: CliOptions,
  helpers: readonly MemberDoc[],
  namespaces: readonly ApiNamespace[],
  groups: readonly ApiGroup[],
): ReadonlyArray<RenderedFile> => [
  {
    path: join(options.outputDir, "index.md"),
    content: renderIndex(namespaces),
  },
  {
    path: join(options.outputDir, "api.md"),
    content: renderApiOverview(helpers, namespaces),
  },
  ...groups.map((group) => ({
    path: join(options.outputDir, `${group.id}.md`),
    content: renderGroup(group),
  })),
];

const ensureParentDir = (path: string): Promise<void> =>
  fs.mkdir(dirname(path), { recursive: true });

const listMarkdownFiles = async (dir: string): Promise<readonly string[]> => {
  const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
  const files: string[] = [];
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await listMarkdownFiles(path)));
    } else if (entry.isFile() && entry.name.endsWith(".md")) {
      files.push(path);
    }
  }
  return files;
};

const writeGeneratedDocs = (
  repoRoot: string,
  outputDir: string,
  files: ReadonlyArray<RenderedFile>,
): Effect.Effect<void, unknown> =>
  Effect.gen(function* () {
    const legacyDir = resolve(repoRoot, LEGACY_OUTPUT_DIR);
    if (legacyDir !== outputDir) {
      yield* Effect.tryPromise(() =>
        fs.rm(legacyDir, { recursive: true, force: true }),
      );
    }

    yield* Effect.tryPromise(() => fs.mkdir(outputDir, { recursive: true }));

    const expected = new Set(files.map((file) => resolve(file.path)));
    const existing = yield* Effect.tryPromise(() => listMarkdownFiles(outputDir));
    for (const file of existing) {
      if (!expected.has(resolve(file))) {
        yield* Effect.tryPromise(() => fs.unlink(file));
      }
    }

    for (const file of files) {
      yield* Effect.tryPromise(() => ensureParentDir(file.path));
      const current = yield* Effect.tryPromise(() =>
        fs.readFile(file.path, "utf8"),
      ).pipe(Effect.catch(() => Effect.succeed(null)));
      if (current === file.content) {
        continue;
      }

      yield* Effect.tryPromise(() =>
        fs.writeFile(file.path, file.content, "utf8"),
      );
    }
  });

const main = (options: CliOptions): Effect.Effect<void, unknown> =>
  Effect.gen(function* () {
    const program = createProgram(options.repoRoot);
    const sourceFile = program.getSourceFile(options.sourceFile);
    if (!sourceFile) {
      fail(`Unable to load ${relative(options.repoRoot, options.sourceFile)}`);
    }

    const checker = program.getTypeChecker();
    const declarations = buildDeclarationMap(program);
    const git = yield* getGitSourceInfo(options.repoRoot);
    const { apiHelpers, namespaces, groups } = collectApiGroups(
      checker,
      declarations,
      options,
      options.includeSourceLinks ? git : null,
    );
    const renderedFiles = renderFiles(options, apiHelpers, namespaces, groups);

    yield* writeGeneratedDocs(options.repoRoot, options.outputDir, renderedFiles);
    yield* Console.log(
      `Generated ${renderedFiles.length} scripting API doc files in ${relative(
        options.repoRoot,
        options.outputDir,
      )}`,
    );
  });

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const options = parseCliOptions(process.argv.slice(2), DEFAULT_REPO_ROOT);

  main(options).pipe(
    Effect.catch((error) =>
      Effect.gen(function* () {
        yield* Console.error(
          error instanceof Error ? error.message : String(error),
        );
        yield* Effect.sync(() => {
          process.exitCode = 1;
        });
      }),
    ),
    NodeRuntime.runMain,
  );
}
