    "| Member | Description |",
    "| --- | --- |",
    "| [`api`](./api/) | Core game and service APIs, grouped by namespace. |",
    "| [`autoZone`](./auto-zone/) | Auto Zone feature controls. |",
    "| [`autoRelogin`](./auto-relogin/) | Auto Relogin feature controls. |",
    "",
    "## API Namespaces",
